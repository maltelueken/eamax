@pytest.fixture(scope="module")
def lba_points():
    return _read_fixture("emc2_lba_pointwise.csv")


def _lba_pointwise_logpdf(d):
    return np.array(
        lba_logpdf(
            jnp.array((d.rt - d.t0).to_numpy()),
            d.v_win.to_numpy(),
            d.sv_win.to_numpy(),
            d.A.to_numpy(),
            (d.A + d.B).to_numpy(),
        ),
    )


def test_lba_logpdf_matches_emc2_where_representable(lba_points):
    d = lba_points
    ours = _lba_pointwise_logpdf(d)
    ref = d.log_pdf.to_numpy()
    above_floor = ~np.isclose(ours, MIN_LL)
    well_conditioned = above_floor & (ours - MIN_LL > HEADROOM_NATS)
    near_floor = above_floor & ~well_conditioned

    assert well_conditioned.sum() > 300
    assert _relerr(ref[well_conditioned], ours[well_conditioned]).max() < 1e-8
    assert _relerr(ref[near_floor], ours[near_floor]).max() < NEAR_FLOOR_TOL


def test_lba_logpdf_floor_is_bounded_against_emc2(lba_points):
    # The complement of the test above: wherever our density has floored, EMC2's value must be
    # at or near the floor too. This is the regression test for the floor being applied to the
    # *density* -- flooring the pre-normalization bracket instead returns
    # `-log(A) - log Phi(v/s)` nats *above* the floor, i.e. a tail overstated rather than
    # clamped, and at A = 0.6, b = 1.8, v = 3.5, s = 1.2, dt = 0.05 that is -22.51 against a
    # true value of e^-146.
    d = lba_points
    ours = _lba_pointwise_logpdf(d)
    floored = np.isclose(ours, MIN_LL)
    assert floored.any()
    assert np.all(ours[floored] == pytest.approx(MIN_LL))
    assert (d.log_pdf.to_numpy()[floored] - MIN_LL).max() < FLOOR_BAND_NATS


def test_lba_logsf_matches_emc2(lba_points):
    d = lba_points
    ours = np.array(
        lba_logsf(
            jnp.array((d.rt - d.t0).to_numpy()),
            d.v_lose.to_numpy(),
            d.sv_lose.to_numpy(),
            d.A.to_numpy(),
            (d.A + d.B).to_numpy(),
        ),
    )
    # No tiering needed here: unlike the Wald survival, the LBA's truncated-normal drift
    # leaves a heavy tail, so EMC2's `1 - plba(...)` stays well conditioned across the fixture.
    assert _relerr(d.log_sf.to_numpy(), ours).max() < 1e-8


def test_lba_race_matches_emc2(lba_points):
    d = lba_points
    b = (d.A + d.B).to_numpy()
    ours = np.array(
        _two_accumulator_race(
            LBA(),
            jnp.array(d.rt.to_numpy()),
            None,
            jnp.array(d.t0.to_numpy()),
            {"v": d.v_win.to_numpy(), "s": d.sv_win.to_numpy(), "A": d.A.to_numpy(), "b": b},
            {"v": d.v_lose.to_numpy(), "s": d.sv_lose.to_numpy(), "A": d.A.to_numpy(), "b": b},
        ),
    )
    ref = np.maximum(d.log_race.to_numpy(), MIN_LL)
    floored = np.isclose(ours, MIN_LL)
    well_conditioned = ~floored & (ours - MIN_LL > HEADROOM_NATS)
    near_floor = ~floored & ~well_conditioned

    assert _relerr(ref[well_conditioned], ours[well_conditioned]).max() < 1e-8
    assert _relerr(ref[near_floor], ours[near_floor]).max() < NEAR_FLOOR_TOL
    # Same band as the pointwise density: where we floor, EMC2 must be near the floor too.
    assert (ref[floored] - MIN_LL).max() < FLOOR_BAND_NATS


def test_lba_total_log_likelihood_matches_emc2():
    truth = _read_header_params("emc2_lba_dataset.csv")
    d = _read_fixture("emc2_lba_dataset.csv")

    rt = jnp.array(d.rt.to_numpy())
    response = jnp.array(d.choice.to_numpy(), dtype=int)
    ones = jnp.ones_like(rt)
    b = truth["A"] + truth["B"]

    params = {
        "v": jnp.stack([truth["v_intercept"] * ones, (truth["v_intercept"] + truth["v_slope"]) * ones]),
        "s": jnp.stack([truth["s_false"] * ones, truth["s_true"] * ones]),
        "A": jnp.stack([truth["A"] * ones, truth["A"] * ones]),
        "b": jnp.stack([b * ones, b * ones]),
    }
    ours = float(
        jnp.sum(race_loglik(rt, response, truth["t0"], lambda t: LBA().log_pdf_sf(t, params))),
    )
    assert _relerr(truth["total_log_likelihood"], ours) < 1e-9
